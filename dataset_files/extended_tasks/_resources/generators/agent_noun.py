#!/usr/bin/env python3
"""Generator for agent_noun task.

Rule: given a verb, output the agent noun formed with -er/-or (the person
or thing that does the action).

Recipe (per new_task_specs.json #89): verb pool = common_verbs.txt plus
alphabetic wordfreq-top-100k words whose getAllLemmas VERB lemma equals
the surface form. Candidates per verb: v+'er' and v+'or'; if v ends in
'e': v+'r' and v[:-1]+'or'; consonant+'y': v[:-1]+'ier'; monosyllabic CVC:
doubled consonant +'er'. Keep the verb iff exactly ONE candidate has
zipf_frequency>=2.2.

Manual-audit note: the zipf-frequency filter only validates that the
derived STRING is a real English word, not that it is semantically the
correct agent noun of that specific verb. It also does not filter out
inputs that are primarily adjectives with a marginal/obscure verb sense
(whose "-er"/"-ier" form is really a comparative, e.g. 'blue'->'bluer',
'stiff'->'stiffer', 'busy'->'busier'). A full manual scan of the ~1230
candidate pairs found and removed two classes of problems:
  1. Adjective/verb polysemes where the sole surviving candidate is the
     comparative form, not an agent noun (removed by excluding any verb
     that also appears in common_adjs.txt).
  2. Coincidental collisions: the derived string is a real English word,
     but an unrelated one (different sense/etymology), not the agent
     noun of the given verb — e.g. 'badge'->'badger' (the animal),
     'butt'->'butter' (the dairy product), 'gate'->'gator', 'curse'-
     >'cursor', 'let'->'letter', 'temp'->'temper', 'tie'->'tier',
     'state'->'stator', 'ledge'->'ledger', 'mist'->'mister', 'ban'-
     >'banner', 'bet'->'better'/'lie'->'lier' (the standard forms are
     the irregular 'bettor'/'liar', not generated by this rule),
     surnames/brand names coincidentally matching (e.g. 'cram'-
     >'cramer', 'ash'->'asher', 'cone'->'conor', 'crock'->'crocker',
     'gel'->'geller', 'jet'->'jeter', 'pry'->'pryor'), and a few
     sensitive/vulgar terms. These specific (verb, candidate) pairs are
     hard-excluded below; nothing else about the recipe is changed.
"""
import json
import os
import random
import re
import sys

from lemminflect import getAllLemmas
from wordfreq import top_n_list, zipf_frequency

HERE = os.path.dirname(os.path.dirname(__file__))
OUT_PATH = os.path.join(os.path.dirname(HERE), "agent_noun.json")

VOWELS = set("aeiou")
ZIPF_THRESHOLD = 2.2

# Verbs whose sole surviving candidate was found by manual audit to be a
# semantically wrong / coincidental match (see module docstring), or a
# sensitive/vulgar term not appropriate for the dataset.
HARD_EXCLUDE_VERBS = {
    "ace", "arm", "ash", "badge", "ball", "ban", "barb", "beam", "belt",
    "bet", "bloom", "bog", "bolt", "bone", "bow", "brain", "bridge",
    "brook", "buckle", "bull", "bunk", "butt", "candle", "cat", "clam",
    "cock", "coke", "cone", "cost", "cow", "cram", "crate", "crock",
    "crowd", "curry", "curse", "demean", "develope", "dole", "down",
    "equate", "err", "fame", "ferry", "fib", "fin", "flow", "foot",
    "fur", "gab", "garb", "gas", "gate", "gel", "geld", "gell", "gird",
    "glass", "grub", "guy", "hark", "harm", "have", "helm", "hie",
    "hone", "horn", "hype", "inn", "jet", "keel", "ken", "lag", "lake",
    "lard", "lathe", "laud", "ledge", "let", "limb", "lust", "mast",
    "mate", "mess", "mist", "mull", "must", "neck", "nest", "nut",
    "oust", "outdo", "pal", "palm", "paste", "peck", "pee", "pen",
    "pep", "phase", "pip", "pond", "poop", "prop", "pry", "pup", "put",
    "rag", "rage", "rain", "rape", "rat", "ref", "reef", "rein", "rend",
    "revolve", "rim", "roost", "rot", "rout", "rut", "sag", "scamp",
    "scat", "scud", "shim", "shin", "shit", "singe", "slat", "slave",
    "snip", "sob", "sop", "stag", "star", "state", "steel", "tail",
    "tamp", "tape", "task", "temp", "tend", "tie", "toss", "tour",
    "trump", "vent", "vine", "vise", "wag", "wage", "wall", "wand",
    "whisk", "wick", "yard",
}

# Verbs that are ALSO in common_adjs.txt (adjective/verb polysemes) are
# dropped by default, because for most such words the sole surviving
# -er/-ier candidate is really the comparative adjective form, not an
# agent noun (e.g. 'busy'->'busier', 'hot'->'hotter', 'true'->'truer').
# These specific ones were manually verified to have a genuine,
# non-comparative agent/instrumental noun sense and are allowed through.
ADJ_OVERLAP_ALLOWLIST = {
    "aggregate", "alternate", "animate", "back", "beat", "blind",
    "broadcast", "buff", "bust", "camp", "chill", "clean", "close",
    "collect", "compact", "cool", "correct", "cream", "damp", "diffuse",
    "direct", "divine", "dress", "elect", "fake", "fell", "fit", "flash",
    "flip", "forward", "game", "head", "idle", "light", "mediate",
    "moderate", "open", "own", "plane", "present", "pretend", "prime",
    "record", "replicate", "roast", "separate", "set", "slack", "span",
    "split", "sound", "stock", "tame", "tan", "top", "trim", "warm",
    "wash", "waste", "wholesale",
}


def is_verb_baseform(w):
    lemmas = getAllLemmas(w)
    return w in lemmas.get("VERB", ())


def count_vowel_groups(w):
    return len(re.findall(r"[aeiouy]+", w))


def is_monosyllabic_cvc(v):
    if len(v) < 3:
        return False
    if v[-1] in ("w", "x", "y"):
        return False
    if v[-1] in VOWELS or v[-2] not in VOWELS or v[-3] in VOWELS:
        return False
    return count_vowel_groups(v) == 1


def candidates(v):
    cands = {v + "er", v + "or"}
    if v.endswith("e"):
        cands.add(v + "r")
        cands.add(v[:-1] + "or")
    if len(v) >= 2 and v.endswith("y") and v[-2] not in VOWELS:
        cands.add(v[:-1] + "ier")
    if is_monosyllabic_cvc(v):
        cands.add(v + v[-1] + "er")
    return cands


def build_pairs():
    words = top_n_list("en", 100000)
    wf_verbs = [
        w for w in words
        if w.isalpha() and w.islower() and len(w) >= 3 and is_verb_baseform(w)
    ]

    with open(os.path.join(HERE, "common_verbs.txt")) as f:
        common_verbs = [line.strip() for line in f if line.strip()]
    common_verbs = [
        w for w in common_verbs if w.isalpha() and w.islower() and len(w) >= 3
    ]

    with open(os.path.join(HERE, "common_adjs.txt")) as f:
        common_adjs = set(line.strip() for line in f if line.strip())

    pool = sorted(set(wf_verbs) | set(common_verbs))
    # Drop verbs that are also common adjectives: for these the sole
    # surviving -er/-ier candidate is almost always the comparative
    # adjective form, not an agent noun (see module docstring), unless
    # manually verified otherwise (ADJ_OVERLAP_ALLOWLIST).
    pool = [
        w for w in pool
        if w not in HARD_EXCLUDE_VERBS
        and (w not in common_adjs or w in ADJ_OVERLAP_ALLOWLIST)
    ]

    pairs = []
    for v in pool:
        passing = [c for c in candidates(v) if zipf_frequency(c, "en") >= ZIPF_THRESHOLD]
        if len(passing) == 1:
            pairs.append((v, passing[0]))
    return pairs


def generate():
    pairs = build_pairs()
    print(f"domain size: {len(pairs)}")

    random.seed(42)
    random.shuffle(pairs)
    pairs = pairs[:1000]

    dataset = [{"input": v, "output": n} for v, n in pairs]

    random.seed(42)
    random.shuffle(dataset)

    seen_inputs = set()
    for item in dataset:
        v, n = item["input"], item["output"]
        assert v not in seen_inputs
        seen_inputs.add(v)
        assert v == v.strip() and n == n.strip()
        passing = [c for c in candidates(v) if zipf_frequency(c, "en") >= ZIPF_THRESHOLD]
        assert passing == [n], (v, n, passing)

    assert len(dataset) == 1000
    assert len(set(d["input"] for d in dataset)) == 1000
    return dataset


if __name__ == "__main__":
    dataset = generate()
    with open(OUT_PATH, "w") as f:
        json.dump(dataset, f)
    print(f"wrote {len(dataset)} examples to {OUT_PATH}")
