def generate():
    seen_cities = set()
    records = []
    for city, country in CITY_COUNTRY:
        assert country in COUNTRY_CONTINENT, f"missing continent for {country}"
        assert city not in seen_cities, f"duplicate city: {city}"
        seen_cities.add(city)
        records.append({"input": city, "output": COUNTRY_CONTINENT[country]})

    random.seed(42)
    random.shuffle(records)
    n = min(1000, len(records))
    dataset = records[:n]

    # self-check: re-derive continent from the lookup tables and compare
    city_to_country = dict(CITY_COUNTRY)
    for item in dataset:
        country = city_to_country[item["input"]]
        assert COUNTRY_CONTINENT[country] == item["output"]

    inputs = [d["input"] for d in dataset]
    assert len(inputs) == len(set(inputs))

    from collections import Counter
    print("total candidates:", len(records))
    print("continent distribution:", Counter(d["output"] for d in dataset))

    return dataset


