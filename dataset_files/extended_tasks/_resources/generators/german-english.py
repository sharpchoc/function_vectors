def main():
    assert len(FACTS) == 1000, f"expected 1000 curated pairs, got {len(FACTS)}"

    inputs = [a for a, b in FACTS]
    outputs = [b for a, b in FACTS]
    assert len(set(inputs)) == len(inputs), "duplicate inputs in FACTS"
    assert len(set(outputs)) == len(outputs), "duplicate outputs in FACTS ((a duplicate output here would mean two different German inputs share an English gloss, which is fine; the real constraint enforced above is unique INPUTS) collision)"
    for a, b in FACTS:
        assert a == a.strip() and b == b.strip(), (a, b)
        assert a and b
        assert " " not in a, f"multi-word input not allowed: {a!r}"

    examples = [{"input": a, "output": b} for a, b in FACTS]

    random.seed(42)
    random.shuffle(examples)

    assert len(examples) == 1000
    assert len({e["input"] for e in examples}) == 1000

    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(here, "..", "..", "german-english.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(examples, f, ensure_ascii=False, indent=1)
    print(f"wrote {len(examples)} examples to {out_path}")


if __name__ == "__main__":
    main()
